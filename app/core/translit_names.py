def pairs() -> dict:
    """'arabic words=English words' entries: Arabic tokens come first, then '=', then the English tokens up to the next Arabic one."""
    import re
    ar = re.compile(r"[\u0600-\u06FF]")
    out, pend, i = {}, [], 0
    toks = NAMES
    while i < len(toks):
        t = toks[i]
        if "=" in t:
            left, right = t.split("=", 1)
            key = " ".join(pend + [left])
            en = [right]
            i += 1
            while i < len(toks) and "=" not in toks[i] and not ar.search(toks[i]):
                en.append(toks[i]); i += 1
            out[key] = " ".join(en)
            pend = []
            continue
        pend.append(t); i += 1
    return out
